import {createHash} from 'node:crypto';
import {copyFileSync,existsSync,mkdirSync,readFileSync,rmSync,writeFileSync} from 'node:fs';
import {join,resolve} from 'node:path';

const mealIds=[
 'pho','chao-ga','com-nam-sang','banh-mi-op-la','bun-bo','mien-ga','xoi-ga','nui-xao-bo','banh-cuon','hu-tieu',
 'com-ga','ga-nam','ca-trua','thit-kho-trung','bo-xao-bong-cai','tom-rim','canh-chua-ca','suon-xao-chua-ngot','ga-kho-gung','dau-hu-nhoi-thit',
 'ca','ga','dau','ca-hap-gung','bo-luc-lac','ga-nuong-mat-ong','tom-xao-rau-cu','canh-ga-la-giang','thit-luon-rau-cu','bun-cha',
];

const curated=JSON.parse(readFileSync('content/curated-extra-recipes.json','utf8'));
const uploadRoot=resolve('.catalog-upload');
const migrationArgument=process.argv.find(argument=>argument.startsWith('--migration='));
const migrationName=migrationArgument?.slice('--migration='.length)??'202607260007_production_catalog_content.sql';
if(!/^\d{14}_[a-z0-9_]+\.sql$/.test(migrationName))throw new Error('Tên migration không hợp lệ.');
const migrationPath=resolve('supabase/migrations',migrationName);
if(existsSync(migrationPath)){
 throw new Error(`Không ghi đè migration đã tồn tại: ${migrationPath}. Hãy truyền --migration với timestamp mới.`);
}
if(existsSync(uploadRoot))rmSync(uploadRoot,{recursive:true});
mkdirSync(uploadRoot,{recursive:true});

const assets=mealIds.map(id=>{
 const source=resolve(`assets/images/meals/${id}.webp`);
 if(!existsSync(source))throw new Error(`Thiếu ảnh: ${source}`);
 const bytes=readFileSync(source);
 const checksum=createHash('sha256').update(bytes).digest('hex').slice(0,16);
 const filename=`${id}-${checksum}.webp`;
 copyFileSync(source,join(uploadRoot,filename));
 return{id,path:`production/${filename}`};
});

const sqlString=value=>`'${String(value).replaceAll("'","''")}'`;
const ingredients=[...new Map(Object.values(curated).flatMap(recipe=>recipe.ingredients).map(([name,,category])=>[
 name.toLocaleLowerCase('vi-VN'),{name,category},
])).values()];

const ingredientValues=ingredients.map(({name,category})=>{
 const slug=`ingredient-${createHash('sha256').update(name.toLocaleLowerCase('vi-VN')).digest('hex').slice(0,16)}`;
 return`  (${sqlString(slug)},${sqlString(name)},${sqlString(category)})`;
}).join(',\n');

const assetValues=assets.map(({id,path})=>`  (${sqlString(id)},${sqlString(path)})`).join(',\n');
const recipeCalls=Object.entries(curated).map(([mealId,recipe])=>{
 const ingredientPayload=recipe.ingredients.map(([name,quantity,category],index)=>({
  id:`${mealId}-ingredient-${index+1}`,name,quantity,category,position:index+1,optional:false,
 }));
 const stepPayload=recipe.steps.map((description,index)=>({
  id:`${mealId}-step-${index+1}`,position:index+1,description,
 }));
 return`select public.replace_meal_recipe(
  ${sqlString(mealId)},
  ${sqlString(JSON.stringify(ingredientPayload))}::jsonb,
  ${sqlString(JSON.stringify(stepPayload))}::jsonb
);`;
}).join('\n\n');

const sql=`-- Generated by scripts/catalog/prepare-production.mjs.
-- The source catalog remains content/curated-extra-recipes.json.

create or replace function public.replace_meal_recipe(
  target_meal_id text,
  target_ingredients jsonb,
  target_steps jsonb
)
returns void
language plpgsql
security definer
set search_path=''
as $$
begin
  if not exists(select 1 from public.meals where id=target_meal_id) then
    raise exception 'Unknown meal: %',target_meal_id;
  end if;
  if jsonb_typeof(target_ingredients)<>'array' or jsonb_array_length(target_ingredients)<2 then
    raise exception 'A recipe requires at least two ingredients';
  end if;
  if jsonb_typeof(target_steps)<>'array' or jsonb_array_length(target_steps)<2 then
    raise exception 'A recipe requires at least two steps';
  end if;

  delete from public.recipe_ingredients where meal_id=target_meal_id;
  delete from public.recipe_steps where meal_id=target_meal_id;

  insert into public.recipe_ingredients(
    id,meal_id,name,quantity,category,available_by_default,position,
    ingredient_id,quantity_value,unit,preparation,optional
  )
  select
    item.id,target_meal_id,item.name,item.quantity,item.category,false,item.position,
    coalesce(item.ingredient_id,catalog.id),item.quantity_value,item.unit,item.preparation,
    coalesce(item.optional,false)
  from jsonb_to_recordset(target_ingredients) as item(
    id text,name text,quantity text,category text,position integer,
    ingredient_id uuid,quantity_value numeric,unit text,preparation text,optional boolean
  )
  left join lateral (
    select id from public.ingredient_catalog
    where lower(name_vi)=lower(item.name)
    order by id limit 1
  ) catalog on true;

  insert into public.recipe_steps(id,meal_id,position,description)
  select item.id,target_meal_id,item.position,item.description
  from jsonb_to_recordset(target_steps) as item(id text,position integer,description text);
end;
$$;

revoke all on function public.replace_meal_recipe(text,jsonb,jsonb) from public,anon,authenticated;
grant execute on function public.replace_meal_recipe(text,jsonb,jsonb) to service_role;

insert into public.ingredient_catalog(slug,name_vi,category)
values
${ingredientValues}
on conflict(slug) do update set
  name_vi=excluded.name_vi,
  category=excluded.category,
  updated_at=now();

create temporary table production_meal_assets(
  meal_id text primary key,
  image_path text not null
) on commit drop;

insert into production_meal_assets(meal_id,image_path)
values
${assetValues};

update public.meals meal
set
  image_path=asset.image_path,
  image_url=null,
  source_type='ai_generated',
  source_name='Daily Meals editorial (AI-assisted)',
  content_license='internal-use',
  content_version=2,
  content_status='published',
  updated_at=now()
from production_meal_assets asset
where meal.id=asset.meal_id;

${recipeCalls}
`;

writeFileSync(migrationPath,sql,'utf8');
console.log(JSON.stringify({meals:mealIds.length,curatedRecipes:Object.keys(curated).length,assets:assets.length,migration:migrationPath,uploadDir:uploadRoot}));
