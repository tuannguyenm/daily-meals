import {readFileSync,writeFileSync} from 'node:fs';
import {resolve} from 'node:path';

const argument=name=>process.argv.find(value=>value.startsWith(`--${name}=`))?.slice(name.length+3);
const sourceFile=argument('source')??'content/home-cooked-expansion.json';
const outputFile=argument('output')??'supabase/migrations/202607280014_home_cooked_expansion.sql';
const imageFolder=argument('image-folder')??'home-cooked-v2';
const contentVersion=Number(argument('content-version')??3);
if(!Number.isInteger(contentVersion)||contentVersion<1)throw new Error('Invalid content version');
const catalog=JSON.parse(readFileSync(resolve(sourceFile),'utf8'));
if(catalog.meals.length!==100)throw new Error(`Expected 100 meals, received ${catalog.meals.length}`);

const quote=value=>`'${String(value).replaceAll("'","''")}'`;
const textArray=values=>`array[${values.map(quote).join(',')}]`;
const mealRows=catalog.meals.map((meal,index)=>` (${[
 quote(meal.id),quote(meal.type),quote(meal.title),quote(meal.summary),textArray(meal.sideDishes),
 meal.cookingTimeMinutes,meal.estimatedCost,meal.servings,textArray(meal.missingIngredients),
 textArray(meal.tags),quote(meal.slug),quote(meal.cuisine),quote(meal.difficulty),
 `${quote(JSON.stringify(meal.nutrition))}::jsonb`,95-(index%31),
 ].join(',')})`);

const uniqueIngredients=[...new Map(
 Object.values(catalog.recipes).flatMap(recipe=>recipe.ingredients)
  .map(ingredient=>[ingredient.name.toLocaleLowerCase('vi-VN'),ingredient]),
).values()];
const ingredientRows=uniqueIngredients.map((ingredient,index)=>` (${[
 quote(`home-v${contentVersion}-${index+1}`),quote(ingredient.name),quote(ingredient.category),
 ].join(',')})`);

const recipeCalls=Object.entries(catalog.recipes).map(([mealId,recipe])=>{
 const ingredients=recipe.ingredients.map((ingredient,index)=>({
  id:`${mealId}-ingredient-${index+1}`,
  name:ingredient.name,
  quantity:ingredient.quantity,
  category:ingredient.category,
  position:index+1,
  preparation:ingredient.preparation??null,
  optional:false,
 }));
 const steps=recipe.steps.map((description,index)=>({
  id:`${mealId}-step-${index+1}`,position:index+1,description,
 }));
 return`select public.replace_meal_recipe(
 ${quote(mealId)},
 ${quote(JSON.stringify(ingredients))}::jsonb,
 ${quote(JSON.stringify(steps))}::jsonb
);`;
}).join('\n');

const sql=`-- Generated by scripts/catalog/generate-home-cooked-migration.mjs.
-- Canonical source: ${sourceFile}.
alter table public.recipe_ingredients
  drop constraint if exists recipe_ingredients_category_check;
alter table public.recipe_ingredients
  add constraint recipe_ingredients_category_check
  check(category in ('Rau củ','Thịt & Hải sản','Gia vị & Khác','Gạo & mì'));

with seed(
 id,type,title,summary,side_dishes,minutes,cost,servings,missing_ingredients,
 tags,slug,cuisine,difficulty,nutrition,popularity
) as(values
${mealRows.join(',\n')}
)
insert into public.meals(
 id,type,title,summary,side_dishes,image_path,image_url,cooking_time_minutes,estimated_cost,
 servings,missing_ingredients,tags,active,slug,cuisine,difficulty,nutrition,content_status,
 source_type,source_name,content_license,popularity_score,content_version,meal_source,
 purchase_time_minutes,price_per_serving
)
select
 seed.id,seed.type,seed.title,seed.summary,seed.side_dishes,
 ${quote(`${imageFolder}/`)}||seed.id||'.webp',null,seed.minutes,seed.cost,
 seed.servings,seed.missing_ingredients,seed.tags,true,seed.slug,seed.cuisine,seed.difficulty,
 seed.nutrition,'published','ai_generated','Daily Meals editorial (AI-assisted)',
 'internal-use',seed.popularity,${contentVersion},'home_cooked',null,null
from seed
on conflict(id) do update set
 type=excluded.type,title=excluded.title,summary=excluded.summary,side_dishes=excluded.side_dishes,
 image_path=excluded.image_path,image_url=null,cooking_time_minutes=excluded.cooking_time_minutes,
 estimated_cost=excluded.estimated_cost,servings=excluded.servings,
 missing_ingredients=excluded.missing_ingredients,tags=excluded.tags,slug=excluded.slug,
 cuisine=excluded.cuisine,difficulty=excluded.difficulty,nutrition=excluded.nutrition,
 content_status='published',source_type=excluded.source_type,source_name=excluded.source_name,
 content_license=excluded.content_license,popularity_score=excluded.popularity_score,
 content_version=${contentVersion},meal_source='home_cooked',purchase_time_minutes=null,
 price_per_serving=null,active=true,updated_at=now();

with ingredient_seed(slug,name_vi,category) as(values
${ingredientRows.join(',\n')}
)
insert into public.ingredient_catalog(slug,name_vi,category)
select seed.slug,seed.name_vi,seed.category
from ingredient_seed seed
where not exists(
 select 1 from public.ingredient_catalog existing
 where lower(existing.name_vi)=lower(seed.name_vi)
)
on conflict(slug) do nothing;

${recipeCalls}
`;

const output=resolve(outputFile);
writeFileSync(output,sql,'utf8');
console.log(JSON.stringify({
 output,meals:catalog.meals.length,ingredients:uniqueIngredients.length,
 recipeIngredients:Object.values(catalog.recipes).reduce((sum,recipe)=>sum+recipe.ingredients.length,0),
 recipeSteps:Object.values(catalog.recipes).reduce((sum,recipe)=>sum+recipe.steps.length,0),
}));
